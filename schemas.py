"""
SceneUI Pro - Core Architecture Data Contracts & Domain Schemas
================================================================
Defines strict Pydantic v2 data models for autonomous multi-modal 
AI narrative production, distributed ComfyUI dispatch, and timeline sync.

Architecture Principles:
- Strong typing and validation for LLM structured outputs (JSON schema enforcement).
- Multi-GPU cluster telemetry and load-balancing state contracts.
- Sub-second WhisperX phoneme alignment and timeline scene bindings.
"""

from __future__ import annotations

from enum import Enum
from typing import Dict, List, Optional
from pydantic import BaseModel, Field, HttpUrl


class LLMProvider(str, Enum):
    """Supported LLM Director providers for story script decomposition."""
    OLLAMA = "ollama"
    OPENAI_GPT4O = "openai_gpt4o"
    GEMINI_FLASH = "gemini_flash"
    NANO_BANANA_2 = "nano_banana_2_flash"


class CameraPerspective(str, Enum):
    """Cinematic camera perspectives assigned to scene generation."""
    WIDE_ESTABLISHING = "wide_establishing"
    MEDIUM_CLOSE_UP = "medium_close_up"
    LOW_ANGLE_HERO = "low_angle_hero"
    OVER_THE_SHOULDER = "over_the_shoulder"
    DUTCH_ANGLE_TENSION = "dutch_angle_tension"
    BIRD_EYE_VIEW = "bird_eye_view"


class CharacterProfile(BaseModel):
    """
    Visual Identity Anchor for consistent character rendering across diffusion seeds.
    Enforces DNA consistency through reference image embeddings and negative prompt constraints.
    """
    id: str = Field(..., description="Unique slug identifier (e.g., 'ALEX_stickman_outfitA')")
    name: str = Field(..., description="Character display name")
    base_gender: str = Field(default="neutral", description="Base character topology template")
    prompt_anchor: str = Field(..., description="Core descriptive visual traits & clothing prompts")
    negative_prompt: str = Field(..., description="Restricted attributes (prevents style drift)")
    reference_image_uri: Optional[str] = Field(default=None, description="Local or cloud URI to locked reference PNG")
    identity_locked: bool = Field(default=True, description="Locks IP-Adapter / reference weight during generation")


class SceneMatrixItem(BaseModel):
    """
    Individual cinematic beat generated by the LLM Director and verified by operator.
    Represents one discrete visual card on the non-linear timeline.
    """
    scene_index: int = Field(..., ge=1, le=100, description="1-based sequence index")
    dialogue_script: str = Field(..., description="Spoken dialogue or narrative voiceover text")
    camera_angle: CameraPerspective = Field(default=CameraPerspective.WIDE_ESTABLISHING)
    image_prompt: str = Field(..., description="Detailed diffusion prompt incorporating style & environment")
    video_motion_prompt: Optional[str] = Field(default=None, description="Motion guidance prompt for Wan2.1 / SVD diffusion")
    character_bindings: List[str] = Field(default_factory=list, description="IDs of referenced characters in this scene")
    assigned_voice_id: str = Field(default="narrator_default", description="Assigned voice profile ID for TTS synthesis")
    
    # Timeline sync fields (populated dynamically post-WhisperX alignment)
    duration_seconds: float = Field(default=3.0, ge=0.5, description="Exact spoken duration locked to speech")
    start_timestamp_ms: int = Field(default=0, ge=0, description="Timeline playback start in milliseconds")
    end_timestamp_ms: int = Field(default=3000, ge=0, description="Timeline playback end in milliseconds")


class VoiceSynthesisConfig(BaseModel):
    """Zero-shot voice cloning and text-to-speech audio rendering parameters."""
    voice_id: str = Field(..., description="Voice identifier or clone preset name")
    clone_audio_sample_path: Optional[str] = Field(default=None, description="Path to 10-15s WAV reference for zero-shot cloning")
    sample_rate: int = Field(default=44100, description="Output PCM sample rate (Hz)")
    pitch_scale: float = Field(default=1.0, ge=0.5, le=2.0)
    speed_factor: float = Field(default=1.0, ge=0.7, le=1.5)
    foley_sfx_path: Optional[str] = Field(default=None, description="Optional diegetic sound effect layered under speech")


class WhisperWordTimestamp(BaseModel):
    """Fine-grained word and phoneme timestamp produced by WhisperX alignment."""
    word: str
    start_sec: float
    end_sec: float
    confidence_score: float = Field(..., ge=0.0, le=1.0)


class MultiGPUNodeTelemetry(BaseModel):
    """Real-time health check and VRAM utilization of worker GPU instances."""
    node_id: str = Field(..., description="Worker identifier (e.g., 'worker-gpu-rtx4090-01')")
    api_endpoint: HttpUrl = Field(..., description="ComfyUI backend REST/WebSocket URL")
    gpu_model: str = Field(default="NVIDIA RTX 4090 24GB")
    vram_total_mb: int = Field(default=24576)
    vram_used_mb: int = Field(default=0)
    active_jobs: int = Field(default=0)
    is_online: bool = Field(default=True)


class MasterRenderSpec(BaseModel):
    """
    Final video assembly instructions passed to hardware-accelerated FFmpeg NVENC pipeline.
    """
    project_slug: str
    resolution_width: int = Field(default=1920, description="Canvas pixel width (e.g. 1920 for 16:9, 1080 for 9:16 Shorts)")
    resolution_height: int = Field(default=1080, description="Canvas pixel height")
    fps: int = Field(default=30, ge=24, le=60)
    bgm_track_path: Optional[str] = Field(default=None, description="Background music file")
    bgm_volume_db: float = Field(default=-18.0, description="Background music volume baseline")
    auto_ducking_attenuation_db: float = Field(default=-12.0, description="Volume reduction applied when dialogue is active")
    enable_burned_in_subtitles: bool = Field(default=True, description="Render dynamic ASS animated caption overlays")
    scenes: List[SceneMatrixItem] = Field(..., min_length=1)
